"""
Test and Verification script for Nexus Policy RAG system.
Tests chunking, dual ChromaDB indexing, retrieval, and fallback mechanisms.
"""

import os
import sys
from pathlib import Path

# Add current directory to path
sys.path.insert(0, str(Path(__file__).resolve().parent))

import config
from chunking import load_and_chunk_all_documents
from vector_store import VectorStore
from rag_engine import RAGEngine


def test_chunking():
    print("\n--- [1] Testing Document Chunking ---")
    chunks = load_and_chunk_all_documents()
    print(f"Total chunks created: {len(chunks)}")
    assert len(chunks) > 0, "No chunks generated!"

    # Verify expected document IDs are present
    doc_ids = {c["metadata"]["doc_id"] for c in chunks}
    print(f"Discovered Document IDs: {doc_ids}")
    assert "FIN-EXP-006" in doc_ids, "Missing Expense Guide"
    assert "IT-SEC-002" in doc_ids, "Missing IT Policy"
    assert "HR-TRV-004" in doc_ids, "Missing Travel Policy"

    print("Sample Chunk Preview:")
    sample = chunks[0]
    print(f"ID: {sample['id']}")
    print(f"Metadata: {sample['metadata']}")
    print(f"Text Preview:\n{sample['text'][:180]}...\n")
    print(" Chunking test passed successfully!")
    return chunks


def test_vector_indexing_and_retrieval():
    print("\n--- [2] Testing ChromaDB Vector Store Indexing ---")
    store = VectorStore()
    index_res = store.index_documents(force_reindex=True)
    print("Indexing result:", index_res)

    stats = store.get_stats()
    print("Collection stats:", stats)

    print("\n--- [3] Testing Retrieval ---")
    test_query = "What is the receipt threshold for expense reimbursement?"
    print(f"Query: '{test_query}'")

    # Try preferred retrieval
    results, provider_used, fallback_reason = store.query(
        query_text=test_query,
        n_results=2,
        preferred_provider="openai"
    )
    print(f"Retrieval provider used: {provider_used}")
    if fallback_reason:
        print(f"Fallback reason: {fallback_reason}")

    for idx, r in enumerate(results, 1):
        meta = r["metadata"]
        print(f"Result {idx}: [{meta['doc_id']}] {meta['section_title']} (Similarity: {r['similarity']:.4f})")
    print(" Retrieval test completed!")


def test_full_rag_pipeline():
    print("\n--- [4] Testing Full RAG Pipeline & Fallback ---")
    engine = RAGEngine()

    # Test 1: Standard query
    q1 = "What is the deadline to submit travel expense claims, and what class of flight is standard?"
    print(f"\nUser Question: {q1}")
    res1 = engine.ask(q1, n_results=2, preferred_provider="openai")
    print(f"Generated by: {res1['llm_provider']} ({res1['model_name']})")
    print(f"Is fallback: {res1['is_fallback']}")
    print(f"Answer:\n{res1['answer']}\n")

    # Test 2: Forced Gemini Fallback Test
    q2 = "Can employees upload confidential company documents to public AI tools?"
    print(f"\nTesting Fallback Mode with Gemini -> Question: {q2}")
    res2 = engine.ask(q2, n_results=2, preferred_provider="gemini")
    print(f"Generated by: {res2['llm_provider']} ({res2['model_name']})")
    print(f"Is fallback: {res2['is_fallback']}")
    print(f"Answer:\n{res2['answer']}\n")

    # Test 3: Simulating OpenAI Failure to verify Automatic Fallback
    q3 = "What should an employee do if a company device is lost or stolen?"
    print(f"\nTesting Automatic Fallback (Simulating OpenAI Failure) -> Question: {q3}")
    # Temporarily corrupt config.OPENAI_API_KEY to simulate key revocation/quota outage
    real_key = config.OPENAI_API_KEY
    try:
        config.OPENAI_API_KEY = "sk-invalid-simulated-key"
        res3 = engine.ask(q3, n_results=2, preferred_provider="openai")
        print(f"Generated by: {res3['llm_provider']} ({res3['model_name']})")
        print(f"Is fallback triggered: {res3['is_fallback']}")
        print(f"Fallback reason: {res3['fallback_reason']}")
        print(f"Answer:\n{res3['answer']}\n")
        assert res3['is_fallback'] is True, "Fallback was not triggered as expected!"
        assert res3['llm_provider'] == "Gemini", "LLM provider should have fallen back to Gemini!"
    finally:
        config.OPENAI_API_KEY = real_key

    print(" Full RAG pipeline & automatic fallback test completed successfully!")


if __name__ == "__main__":
    test_chunking()
    test_vector_indexing_and_retrieval()
    test_full_rag_pipeline()

